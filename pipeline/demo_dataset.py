"""Deterministic, persisted synthetic dashboard fixture.

This fixture is deliberately separate from the official biosignal-mock executable.
It is generated from a fixed seed, written as JSON Lines once, and used to populate
both local and cloud SQLite stores so every dashboard view reads the same records.
"""
from __future__ import annotations

import hashlib
import hmac
import json
import math
import random
import time
from pathlib import Path
from typing import Any

from .db import CHANNELS, Database, SAMPLE_RATE, canonical_json
from .processing import process_offline_results, process_online_results

DEMO_SESSION_ID = "maya-demo-seed7-v1"
DEMO_SEED = 7
BUNDLED_DEMO_DATASET_PATH = Path(__file__).resolve().parent.parent / "data" / "fixtures" / "synthetic_demo_seed7.jsonl"
DEMO_DURATION_SECONDS = 30
DEMO_GAP_SENSOR = 2
DEMO_GAP_START = 4_800
DEMO_GAP_END = 4_839
DEMO_OFFLINE_WINDOWS = (15, 16, 17)
DEMO_NOTICE = (
    "Deterministic synthetic demo fixture (seed 7), stored in local and cloud SQLite databases. "
    "Not generated by the official biosignal-mock and not for clinical use."
)


def _sample_rows(duration_seconds: int = DEMO_DURATION_SECONDS, seed: int = DEMO_SEED) -> list[dict[str, Any]]:
    """Generate a reproducible 400 Hz stream with three pulse-rate segments."""
    rng_ecg = random.Random(seed)
    rng_aux = random.Random(seed + 1)
    rows: list[dict[str, Any]] = []
    total_samples = duration_seconds * SAMPLE_RATE
    segment_samples = 10 * SAMPLE_RATE

    for index in range(total_samples):
        segment = min(index // segment_samples, 2)
        segment_start = segment * segment_samples
        bpm = (60, 90, 72)[segment]
        period = max(1, round(SAMPLE_RATE * 60 / bpm))
        phase = (index - segment_start) % period
        peak_phase = period // 2
        distance = min(abs(phase - peak_phase), abs(phase - peak_phase - period), abs(phase - peak_phase + period))
        pulse = round(2_400 * (1 - distance / 7)) if distance < 7 else 0
        channel_2 = 300 + pulse + rng_ecg.randint(-6, 6)
        sensor_1_values = [round(channel_2 * 0.6), channel_2, round(channel_2 * 1.3)]
        rows.append({"session_id": DEMO_SESSION_ID, "sensor": 1, "index": index, "values": sensor_1_values})

        # A documented, intentional 40-sample sensor-2 gap at 12 seconds lets the
        # integrity view demonstrate the loss ledger without hiding or inventing data.
        if not (DEMO_GAP_SENSOR == 2 and DEMO_GAP_START <= index <= DEMO_GAP_END):
            slow_a = round(1_800 * math.sin(2 * math.pi * index / (SAMPLE_RATE * 9)))
            slow_b = round(650 * math.sin(2 * math.pi * index / (SAMPLE_RATE * 5)))
            sensor_2_values = [400_000 + slow_a + rng_aux.randint(-180, 180),
                               150_000 + slow_b + rng_aux.randint(-90, 90)]
            rows.append({"session_id": DEMO_SESSION_ID, "sensor": 2, "index": index, "values": sensor_2_values})
    return rows


def _loss_rows() -> list[dict[str, Any]]:
    return [{
        "session_id": DEMO_SESSION_ID,
        "sensor": DEMO_GAP_SENSOR,
        "from_index": DEMO_GAP_START,
        "to_index": DEMO_GAP_END,
        "reason": "synthetic_demo_fault: controlled 40-sample sensor-2 gap at 12 seconds",
    }]


def _window_modes(duration_seconds: int = DEMO_DURATION_SECONDS) -> list[dict[str, Any]]:
    now = time.time()
    rows: list[dict[str, Any]] = []
    for window_index in range(duration_seconds):
        mode = "offline" if window_index in DEMO_OFFLINE_WINDOWS else "online"
        rows.append({"session_id": DEMO_SESSION_ID, "window_index": window_index, "mode": mode,
                     "prior_peak_index": None, "assigned_at": now})
    return rows


def _fixture_data_lines(samples: list[dict[str, Any]], losses: list[dict[str, Any]]) -> list[str]:
    records: list[dict[str, Any]] = []
    for row in samples:
        records.append({"type": "sample", "session_id": row["session_id"], "sensor": row["sensor"],
                        "index": row["index"], "values": row["values"]})
    for row in losses:
        records.append({"type": "loss", **row})
    records.sort(key=lambda row: (
        0 if row["type"] == "sample" else 1,
        int(row.get("index", row.get("from_index", 0))),
        int(row.get("sensor", 0)),
    ))
    return [canonical_json(record) for record in records]


def _manifest(samples: list[dict[str, Any]], losses: list[dict[str, Any]], data_lines: list[str]) -> dict[str, Any]:
    return {
        "type": "manifest",
        "dataset_id": DEMO_SESSION_ID,
        "generator": "pipeline.demo_dataset deterministic synthetic generator",
        "seed": DEMO_SEED,
        "duration_seconds": DEMO_DURATION_SECONDS,
        "sample_rate_hz": SAMPLE_RATE,
        "sensor_1_channel_count": CHANNELS[1],
        "sensor_2_channel_count": CHANNELS[2],
        "sample_rows": len(samples),
        "sensor_1_sample_count": DEMO_DURATION_SECONDS * SAMPLE_RATE,
        "sensor_2_sample_count": DEMO_DURATION_SECONDS * SAMPLE_RATE - (DEMO_GAP_END - DEMO_GAP_START + 1),
        "window_count": DEMO_DURATION_SECONDS,
        "offline_windows": list(DEMO_OFFLINE_WINDOWS),
        "loss_records": len(losses),
        "controlled_gap": {"sensor": DEMO_GAP_SENSOR, "from_index": DEMO_GAP_START, "to_index": DEMO_GAP_END},
        "sha256": hashlib.sha256(("\n".join(data_lines) + "\n").encode("utf-8")).hexdigest(),
        "notice": DEMO_NOTICE,
    }


def _write_dataset_file(path: Path, samples: list[dict[str, Any]], losses: list[dict[str, Any]]) -> dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True)
    data_lines = _fixture_data_lines(samples, losses)
    manifest = _manifest(samples, losses, data_lines)
    temp = path.with_suffix(path.suffix + ".tmp")
    with temp.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(canonical_json(manifest) + "\n")
        for line in data_lines:
            handle.write(line + "\n")
        handle.flush()
    temp.replace(path)
    return manifest


def _load_dataset_file(path: Path) -> tuple[dict[str, Any], list[dict[str, Any]], list[dict[str, Any]]]:
    with path.open("r", encoding="utf-8") as handle:
        first = handle.readline()
        if not first:
            raise ValueError("Synthetic demo dataset file is empty")
        manifest = json.loads(first)
        if manifest.get("type") != "manifest" or manifest.get("dataset_id") != DEMO_SESSION_ID:
            raise ValueError("Synthetic demo dataset manifest is not recognized")
        samples: list[dict[str, Any]] = []
        losses: list[dict[str, Any]] = []
        data_lines: list[str] = []
        for line in handle:
            if not line.strip():
                continue
            record = json.loads(line)
            data_lines.append(canonical_json(record))
            if record.get("type") == "sample":
                samples.append({"session_id": record["session_id"], "sensor": int(record["sensor"]),
                                "index": int(record["index"]), "values": [int(value) for value in record["values"]]})
            elif record.get("type") == "loss":
                losses.append({"session_id": record["session_id"], "sensor": int(record["sensor"]),
                               "from_index": int(record["from_index"]), "to_index": record.get("to_index"),
                               "reason": str(record["reason"])})
            else:
                raise ValueError("Synthetic demo dataset contains an unknown record type")
    digest = hashlib.sha256(("\n".join(data_lines) + "\n").encode("utf-8")).hexdigest()
    if not hmac.compare_digest(digest, str(manifest.get("sha256", ""))):
        raise ValueError("Synthetic demo dataset checksum does not match; reset the demo dataset and seed it again")
    if len(samples) != int(manifest.get("sample_rows", -1)) or len(losses) != int(manifest.get("loss_records", -1)):
        raise ValueError("Synthetic demo dataset counts do not match its manifest")
    return manifest, samples, losses


def _session_counts(database: Database, session_id: str) -> tuple[int, int, int, int]:
    with database.connect() as conn:
        sample_count = int(conn.execute("SELECT COUNT(*) FROM samples WHERE session_id=?", (session_id,)).fetchone()[0])
        loss_count = int(conn.execute("SELECT COUNT(*) FROM losses WHERE session_id=?", (session_id,)).fetchone()[0])
        result_count = int(conn.execute("SELECT COUNT(*) FROM results WHERE session_id=?", (session_id,)).fetchone()[0])
        pending_samples = int(conn.execute("SELECT COUNT(*) FROM samples WHERE session_id=? AND uploaded=0", (session_id,)).fetchone()[0])
    return sample_count, loss_count, result_count, pending_samples


def _export_session_as_fixture(path: Path, database: Database, session_id: str) -> dict[str, Any]:
    with database.connect() as conn:
        rows = conn.execute(
            "SELECT sensor,sample_index,values_json FROM samples WHERE session_id=? ORDER BY sample_index,sensor",
            (session_id,),
        ).fetchall()
        loss_rows = conn.execute(
            "SELECT sensor,from_index,to_index,reason FROM losses WHERE session_id=? ORDER BY sensor,from_index",
            (session_id,),
        ).fetchall()
    samples = [{"session_id": session_id, "sensor": int(row["sensor"]), "index": int(row["sample_index"]),
                "values": json.loads(row["values_json"])} for row in rows]
    losses = [{"session_id": session_id, "sensor": int(row["sensor"]), "from_index": int(row["from_index"]),
               "to_index": None if row["to_index"] is None else int(row["to_index"]), "reason": str(row["reason"])} for row in loss_rows]
    return _write_dataset_file(path, samples, losses)


def seed_persistent_demo(cloud_db: Database, device_db: Database, dataset_path: str | Path) -> dict[str, Any]:
    """Populate both SQLite stores from one persistent deterministic dataset.

    Repeated calls are idempotent. When the fixture file exists, it is the source of
    truth for repair/reseed; when both stores already hold the complete session, a
    missing JSONL file is reconstructed from persisted database records.
    """
    path = Path(dataset_path).expanduser().resolve()
    expected_rows = DEMO_DURATION_SECONDS * SAMPLE_RATE * 2 - (DEMO_GAP_END - DEMO_GAP_START + 1)
    cloud_counts = _session_counts(cloud_db, DEMO_SESSION_ID)
    device_counts = _session_counts(device_db, DEMO_SESSION_ID)
    expected_result_count = DEMO_DURATION_SECONDS
    stored_complete = (
        cloud_counts == (expected_rows, 1, expected_result_count, 0)
        and device_counts == (expected_rows, 1, len(DEMO_OFFLINE_WINDOWS), 0)
    )
    if stored_complete:
        manifest = _load_dataset_file(path)[0] if path.is_file() else _export_session_as_fixture(path, cloud_db, DEMO_SESSION_ID)
        return _seed_response(manifest, cloud_db, device_db, path, already_present=True)

    if path.is_file():
        # Once materialized locally, the JSONL file is authoritative for subsequent loads.
        manifest, samples, losses = _load_dataset_file(path)
    elif BUNDLED_DEMO_DATASET_PATH.is_file():
        # A checked-in fixture gives reviewers the same starter data. Copy its records
        # into the runtime path, validate that copy, then use it for all DB insertion.
        _bundled_manifest, samples, losses = _load_dataset_file(BUNDLED_DEMO_DATASET_PATH)
        _write_dataset_file(path, samples, losses)
        manifest, samples, losses = _load_dataset_file(path)
    else:
        # Fallback for source distributions that intentionally omit the bundled fixture.
        samples = _sample_rows()
        losses = _loss_rows()
        _write_dataset_file(path, samples, losses)
        # Validate the file we just materialized so later steps always consume the persisted copy.
        manifest, samples, losses = _load_dataset_file(path)

    window_modes = _window_modes(int(manifest["duration_seconds"]))
    sample_stats_device = device_db.add_samples(samples, uploaded=False)
    sample_stats_cloud = cloud_db.add_samples(samples, uploaded=True)
    device_db.add_losses(losses, uploaded=False)
    cloud_db.add_losses(losses, uploaded=True)
    device_db.insert_window_modes(window_modes, uploaded=False)
    cloud_db.insert_window_modes(window_modes, uploaded=True)
    device_db.mark_session_ended(DEMO_SESSION_ID)
    cloud_db.mark_session_ended(DEMO_SESSION_ID)
    device_db.set_meta("current_mode", "online")
    device_db.add_event("demo_dataset_seeded", "Persisted deterministic synthetic dataset (seed 7); includes one explicitly recorded controlled gap and a three-window offline segment.", DEMO_SESSION_ID)

    process_offline_results(device_db, DEMO_SESSION_ID)
    process_online_results(cloud_db, DEMO_SESSION_ID)
    device_results = device_db.results_for_session(DEMO_SESSION_ID)
    offline_rows = [{"session_id": DEMO_SESSION_ID, "window_index": int(row["window_index"]), "mode": "offline", "result": row}
                    for row in device_results if row.get("mode") == "offline"]
    cloud_db.insert_offline_results(offline_rows, uploaded=True)

    # The fixture is intentionally seeded into both local stores for a self-contained,
    # reproducible dashboard. Mark the mirrored device rows acknowledged only after the
    # cloud-side rows and computed results have been persisted.
    device_db.mark_uploaded(samples=samples, losses=losses, window_modes=window_modes, offline_results=offline_rows)
    return _seed_response(manifest, cloud_db, device_db, path, already_present=False,
                          sample_insert_stats={"device": sample_stats_device, "cloud": sample_stats_cloud})


def _seed_response(manifest: dict[str, Any], cloud_db: Database, device_db: Database, path: Path,
                   *, already_present: bool, sample_insert_stats: dict[str, Any] | None = None) -> dict[str, Any]:
    cloud_counts = _session_counts(cloud_db, DEMO_SESSION_ID)
    device_counts = _session_counts(device_db, DEMO_SESSION_ID)
    with cloud_db.connect() as conn:
        online_windows = int(conn.execute("SELECT COUNT(*) FROM results WHERE session_id=? AND mode='online'", (DEMO_SESSION_ID,)).fetchone()[0])
        offline_windows = int(conn.execute("SELECT COUNT(*) FROM results WHERE session_id=? AND mode='offline'", (DEMO_SESSION_ID,)).fetchone()[0])
    return {
        "ok": True,
        "already_present": already_present,
        "session_id": DEMO_SESSION_ID,
        "seed": int(manifest["seed"]),
        "sample_rate_hz": int(manifest["sample_rate_hz"]),
        "duration_seconds": int(manifest["duration_seconds"]),
        "sample_rows": int(manifest["sample_rows"]),
        "sensor_1_sample_count": int(manifest["sensor_1_sample_count"]),
        "sensor_2_sample_count": int(manifest["sensor_2_sample_count"]),
        "loss_records": int(manifest["loss_records"]),
        "window_count": int(manifest["window_count"]),
        "online_windows": online_windows,
        "offline_windows": offline_windows,
        "sha256": str(manifest["sha256"]),
        "dataset_file": str(path.name),
        "cloud": {"sample_rows": cloud_counts[0], "loss_records": cloud_counts[1], "results": cloud_counts[2], "pending_samples": cloud_counts[3]},
        "device": {"sample_rows": device_counts[0], "loss_records": device_counts[1], "results": device_counts[2], "pending_samples": device_counts[3]},
        "sample_insert_stats": sample_insert_stats,
        "notice": DEMO_NOTICE,
    }
